-- ══ התראת push בסוף תקופת ליווי / חודש ══
--
-- renewal-nudge שלח עד היום הודעת צ'אט בלבד, שבוע לפני הסוף — ושום
-- דבר ברגע שהתקופה נגמרה. עכשיו הוא שולח push בשני מקרים:
--
--   1. מנוי בחידוש אוטומטי: run_auto_renewals (03:10) האריך אותו
--      ורשם חיוב לחודש החדש. בשעה 05:00 הלקוח מקבל "חודש חדש
--      בליווי התחיל — יתרה לתשלום X ₪".
--   2. מנוי בלי חידוש אוטומטי: התקופה הסתיימה אתמול. הלקוח מקבל
--      "תקופת הליווי הסתיימה — כדי להמשיך, הסדר את התשלום".
--
-- שתי העמודות מונעות כפילות: כל אחת שומרת על מה כבר נשלחה התראה,
-- כך שהרצה חוזרת של הפונקציה באותו יום לא מקפיצה שוב.
--
-- אדיטיבי בלבד. NULL = טרם נשלח. הרצה חוזרת בטוחה.

ALTER TABLE clients
  ADD COLUMN IF NOT EXISTS period_end_push date,   -- ה-coaching_end שעליו כבר נשלח "הסתיים"
  ADD COLUMN IF NOT EXISTS charge_push_at  date;   -- היום שבו נשלח "חודש חדש — יתרה לתשלום"

COMMENT ON COLUMN clients.period_end_push IS
  'סוף התקופה שעליו כבר נשלחה התראת "הליווי הסתיים". מונע התראה כפולה.';
COMMENT ON COLUMN clients.charge_push_at IS
  'היום שבו נשלחה התראת "חודש חדש — יתרה לתשלום". מונע התראה כפולה באותו יום.';
