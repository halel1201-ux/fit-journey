-- ══ האינדקס שחסר על הטבלה המרכזית ══
--
-- clients(email) היא העמודה שכל כניסה למערכת נשאלת לפיה — גם בפאנל
-- המתאמן, גם בפאנל המאמן וגם במסך ההתחברות. לכל טבלה אחרת בפרויקט
-- יש אינדקס; דווקא לה לא היה. בלי אינדקס כל קריאה סורקת את הטבלה
-- כולה, ומדיניות ההרשאות מורצת על כל שורה בדרך.
--
-- המדידה שנרשמה ב-21/08: השאילתה חזרה ב-2.4 עד 12 שניות, ובקצה 44.
-- כשהזמן חוצה את מגבלת המסד השאילתה חוזרת בשגיאה — והמתאמן ראה
-- "ממתין לאישור מאמן" למרות שהשורה שלו קיימת ותקינה.
--
-- הרצה חוזרת אינה מזיקה: IF NOT EXISTS.

CREATE INDEX IF NOT EXISTS idx_clients_email ON clients(email);
CREATE INDEX IF NOT EXISTS idx_clients_coach ON clients(coach_email);

ANALYZE clients;
