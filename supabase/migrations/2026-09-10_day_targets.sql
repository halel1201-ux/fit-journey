-- ══ יעדי קלוריות לפי סוג יום ══
--
-- מה שהמסד כבר מספר על השימוש בפועל (נבדק לפני שנכתב):
--   53 תפריטים · 18 מהם מתייגים ארוחות לפי סוג יום
--   15 מתוך ה-18 מתייגים רק ארוחות של יום אימון
--    3 מתייגים אימון וגם מנוחה
--    0 משתמשים ב-target
--
-- כלומר אף מאמן לא בונה שלושה ימים נפרדים. מה שקורה בפועל הוא
-- תפריט בסיס ועוד שתיים-שלוש ארוחות ליום אימון. העמודה הזאת לא
-- משנה את המודל — היא רק מאפשרת למאמן להצהיר יעד, כשהמספר
-- שמוצג ממשיך להיגזר מהארוחות עצמן.
--
-- NULL = בדיוק ההתנהגות של היום. אין מיגרציה של נתונים.
--
-- הרצה חוזרת בטוחה.

ALTER TABLE nutrition_plans
  ADD COLUMN IF NOT EXISTS day_targets jsonb;

COMMENT ON COLUMN nutrition_plans.day_targets IS
  'יעד קלוריות לכל סוג יום: {"training":2400,"rest":2100,"target":2600}. NULL = לא הוגדרו יעדים, והמספר נגזר מסכום הארוחות.';
